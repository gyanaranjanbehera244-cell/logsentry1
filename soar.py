"""
LOGSENTRY SOAR Engine (Security Orchestration, Automation and Response)
Generates real defensive containment scripts, firewall commands, Sigma rules, and SOC tickets.
"""

from datetime import datetime

def generate_containment_scripts(ip, incident_title, severity):
    """Generates ready-to-execute containment commands across major platforms."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    linux_cmd = f"""# ====================================================
# LINUX FIREWALL CONTAINMENT (iptables & nftables)
# Incident: {incident_title}
# Target IP: {ip} | Generated: {timestamp}
# ====================================================
# Immediate drop in raw prerouting (zero kernel overhead):
sudo iptables -I INPUT -s {ip} -j DROP
sudo iptables -I FORWARD -s {ip} -j DROP

# Or using modern nftables:
sudo nft add element inet filter blackhole {{ {ip} }}

# Log containment action in audit log:
logger -p auth.crit "LOGSENTRY SOAR: Blocked malicious source {ip} due to {incident_title}"
"""

    windows_cmd = f"""# ====================================================
# WINDOWS DEFENDER FIREWALL CONTAINMENT (PowerShell)
# Incident: {incident_title}
# Target IP: {ip} | Generated: {timestamp}
# ====================================================
New-NetFirewallRule -DisplayName "LOGSENTRY-BLOCK-{ip}" `
    -Direction Inbound `
    -Action Block `
    -RemoteAddress {ip} `
    -Description "Automated SOAR block for {incident_title}"

# Terminate active SMB / RDP sessions:
Get-SmbSession | Where-Object {{ $_.ClientComputerName -eq '{ip}' }} | Close-SmbSession -Force
Write-Host "[+] Malicious IP {ip} successfully contained." -ForegroundColor Red
"""

    aws_cmd = f"""# ====================================================
# AWS VPC NETWORK ACL CONTAINMENT (AWS CLI)
# Incident: {incident_title}
# Target IP: {ip}/32 | Generated: {timestamp}
# ====================================================
aws ec2 create-network-acl-entry \\
    --network-acl-id acl-0123456789abcdef0 \\
    --ingress \\
    --rule-number 100 \\
    --protocol -1 \\
    --port-range From=0,To=0 \\
    --cidr-block {ip}/32 \\
    --rule-action deny

# Optional: Add to AWS WAF IP Set
# aws wafv2 update-ip-set --name "LogSentry-Blocklist" ...
"""

    cloudflare_cmd = f"""# ====================================================
# CLOUDFLARE WAF / EDGE ACCESS RULE (curl API)
# ====================================================
curl -X POST "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/firewall/access_rules/rules" \\
     -H "Authorization: Bearer $CF_API_TOKEN" \\
     -H "Content-Type: application/json" \\
     --data '{{"mode":"block","configuration":{{"target":"ip","value":"{ip}"}},"notes":"LOGSENTRY SOAR - {incident_title}"}}'
"""

    return {
        "linux": linux_cmd,
        "windows": windows_cmd,
        "aws": aws_cmd,
        "cloudflare": cloudflare_cmd
    }

def generate_sigma_rule(incident):
    """
    Generates a standardized Sigma detection rule (YAML).
    Can be ingested directly by Splunk, Microsoft Sentinel, Elastic, and QRadar.
    """
    clean_title = incident["title"].replace('"', '')
    return f"""title: {clean_title} - Auto-Generated by LOGSENTRY
id: logsentry-{abs(hash(incident['ip'] + incident['title'])) % 100000000}
status: experimental
description: Automated detection rule generated by LOGSENTRY based on observed attack behavior from {incident['ip']}
references:
    - https://attack.mitre.org/techniques/T1110/
author: LOGSENTRY Autonomous Defense Engine
date: {datetime.now().strftime('%Y/%m/%d')}
logsource:
    category: authentication
    product: any
detection:
    selection_ip:
        src_ip: '{incident["ip"]}'
    selection_event:
        action:
            - 'failed'
            - 'privilege_change'
            - 'sensitive_access'
    condition: selection_ip and selection_event
fields:
    - src_ip
    - user
    - action
falsepositives:
    - Authorized penetration testing
    - Misconfigured administrative automation
level: {incident['severity'].lower()}
tags:
    - attack.credential_access
    - attack.privilege_escalation
    - attack.t1110
    - attack.t1098
"""

def generate_soc_ticket(incident):
    """Generates an enterprise Jira / ServiceNow / TheHive incident ticket markdown."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    evidence_bullets = "\n".join([f"* {e}" for e in incident["evidence"]])
    remediation_bullets = "\n".join([f"* [ ] {r}" for r in incident["recommendations"]])
    
    return f"""# [INCIDENT-{incident['severity'].upper()}] {incident['title']}
**Target Entity / Source:** `{incident['ip']}`
**Severity:** `{incident['severity']}` | **Calculated Risk Score:** `{incident['risk_score']}/100`
**Detected At:** {now_str}
**Detection Engine:** LOGSENTRY Hybrid (Rule-Based Correlation + ML Isolation Forest)

---

## 1. Executive Summary
{incident['summary']}

## 2. Forensic Evidence Observed
{evidence_bullets}

## 3. Recommended Containment Playbook
{remediation_bullets}

## 4. Analyst Notes & Sign-off
* **Investigating Analyst:** SOC-Tier-2
* **Disposition:** [ ] Confirmed Malicious  [ ] False Positive  [ ] Authorized Pentest
* **Containment Executed:** [ ] Yes  [ ] No
"""
